pub fn encode_png(img: &RgbaImage) -> Result<Vec<u8>> {
    let mut out = Vec::new();
    PngEncoder::new_with_quality(&mut out, CompressionType::Fast, FilterType::Adaptive)
        .write_image(img.as_raw(), img.width(), img.height(), ExtendedColorType::Rgba8)
        .map_err(|e| AppError::Other(format!("PNG encode: {e}")))?;
    Ok(out)
}

pub fn save_png(img: &RgbaImage, path: &Path) -> Result<()> {
    std::fs::write(path, encode_png(img)?)?;
    Ok(())
}

/// Encodes an image and writes it into the output dir; returns (png bytes, path).
pub fn output(img: &RgbaImage, prefix: &str) -> Result<(Vec<u8>, PathBuf)> {
    let png = encode_png(img)?;
    let nanos = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap_or_default().as_nanos();
    let path = CONFIG.output_dir.join(format!("{prefix}_{nanos}.png"));
    if let Err(e) = std::fs::write(&path, &png) {
        log::warn!("保存图片失败 {}: {e}", path.display());
    }
    Ok((png, std::fs::canonicalize(&path).unwrap_or(path)))
}
